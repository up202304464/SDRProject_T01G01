def argument_parser():
    parser = ArgumentParser()
    parser.add_argument(
        "--min-plateau", dest="min_plateau", type=intx, default=2,
        help="Set min_plateau [default=%(default)r]")
    parser.add_argument(
        "--threshold", dest="threshold", type=eng_float, default=eng_notation.num_to_str(float(0.56)),
        help="Set threshold [default=%(default)r]")
    return parser


def main(top_block_cls=week_04_s2v, options=None):
    if options is None:
        options = argument_parser().parse_args()

    qapp = Qt.QApplication(sys.argv)

    tb = top_block_cls(min_plateau=options.min_plateau, threshold=options.threshold)

    tb.start()

    tb.show()

    def sig_handler(sig=None, frame=None):
        tb.stop()
        tb.wait()

        Qt.QApplication.quit()

    signal.signal(signal.SIGINT, sig_handler)
    signal.signal(signal.SIGTERM, sig_handler)

    timer = Qt.QTimer()
    timer.start(500)
    timer.timeout.connect(lambda: None)

    qapp.exec_()

if __name__ == '__main__':
    main()
